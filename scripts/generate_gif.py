#!/usr/bin/env python3
"""
Prism Headless Frame to GIF Converter
Reads a sequence of PPM (P6) frames generated by Prism and stitches them into an animated GIF.
Usage:
    python3 scripts/generate_gif.py --pattern "frame_*.ppm" --output demo.gif --fps 30
"""

import sys
import glob
import argparse

def parse_ppm(filepath):
    with open(filepath, 'rb') as f:
        magic = f.readline().strip()
        if magic != b'P6':
            raise ValueError(f"Unsupported format: {magic}")
        # Skip comments
        line = f.readline()
        while line.startswith(b'#'):
            line = f.readline()
        width, height = map(int, line.strip().split())
        max_val = int(f.readline().strip())
        data = f.read(width * height * 3)
    return width, height, data

def main():
    parser = argparse.ArgumentParser(description="Convert PPM sequence to animated GIF")
    parser.add_argument("--pattern", default="*.ppm", help="Glob pattern for PPM frames")
    parser.add_argument("--output", default="prism_demo.gif", help="Output GIF path")
    parser.add_argument("--fps", type=int, default=30, help="Frames per second")
    args = parser.parse_args()

    files = sorted(glob.glob(args.pattern))
    if not files:
        print(f"No files found matching pattern '{args.pattern}'")
        return 1

    print(f"Found {len(files)} frames. Converting to GIF...")

    try:
        from PIL import Image
        images = []
        for file in files:
            w, h, data = parse_ppm(file)
            img = Image.frombytes('RGB', (w, h), data)
            images.append(img)
        
        duration = int(1000 / args.fps)
        images[0].save(
            args.output,
            save_all=True,
            append_images=images[1:],
            duration=duration,
            loop=0
        )
        print(f"Successfully generated animated GIF: {args.output}")
    except ImportError:
        print("Pillow (PIL) not installed. Install with 'pip install pillow' to generate GIF.")
        print(f"PPM frames preserved ({len(files)} files).")
        return 0

    return 0

if __name__ == "__main__":
    sys.exit(main())
